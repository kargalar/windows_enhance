export type TranslationKey = keyof typeof translations.en;

let activeLang: Language = 'en';

export function setLanguage(lang: string) {
  activeLang = lang.toLowerCase() === 'tr' ? 'tr' : 'en';
}

export function getLanguage(): Language {
  return activeLang;
}

export function t(key: TranslationKey, lang?: string, params?: Record<string, string | number>): string {
  const currentLang = (lang?.toLowerCase() === 'tr' ? 'tr' : (lang?.toLowerCase() === 'en' ? 'en' : activeLang)) as Language;
  let str: string = (translations[currentLang] as Record<string, string>)[key] ?? (translations.en as Record<string, string>)[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    }
  }
  return str;
}
