        if (a == b) return 0.0;
        var la = char.ToLowerInvariant(a);
        var lb = char.ToLowerInvariant(b);
        if (la == lb) return 0.0;

        // Turkish diacritic equivalence bonus (e.g. s <-> ş, c <-> ç, o <-> ö, u <-> ü, g <-> ğ, i <-> ı)
        if (IsTurkishDiacriticPair(la, lb)) return 0.25;

        if (KeyCoordinates.TryGetValue(la, out var posA) && KeyCoordinates.TryGetValue(lb, out var posB))
        {
            var dr = posA.Row - posB.Row;
            var dc = posA.Col - posB.Col;
            return Math.Sqrt(dr * dr + dc * dc);
        }

        return 3.0; // Default distance for unknown/distant keys
    }

    private static bool IsTurkishDiacriticPair(char a, char b) =>
        (a == 'c' && b == 'ç') || (a == 'ç' && b == 'c') ||
        (a == 'g' && b == 'ğ') || (a == 'ğ' && b == 'g') ||
        (a == 'i' && b == 'ı') || (a == 'ı' && b == 'i') ||
        (a == 'o' && b == 'ö') || (a == 'ö' && b == 'o') ||
        (a == 's' && b == 'ş') || (a == 'ş' && b == 's') ||
        (a == 'u' && b == 'ü') || (a == 'ü' && b == 'u');

