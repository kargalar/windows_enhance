    private static readonly Dictionary<string, string> EnToTr = new(StringComparer.OrdinalIgnoreCase);

    static Localization()
    {
        foreach (var (k, v) in TrToEn)
        {
            if (!EnToTr.ContainsKey(v))
                EnToTr[v] = k;
        }
    }

    public static string Get(string? text, string? language = null)
    {
        if (string.IsNullOrEmpty(text)) return text ?? string.Empty;
        var lang = Normalize(language ?? _currentLanguage);

        if (lang == "en")
        {
            if (TrToEn.TryGetValue(text, out var en)) return en;
            return text;
        }
        else // tr
        {
            if (EnToTr.TryGetValue(text, out var tr)) return tr;
            return text;
        }
    }

    public static string Tr(string turkishText, string englishText, string? language = null) =>
        IsTurkish(language) ? turkishText : englishText;
